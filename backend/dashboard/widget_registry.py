def filter_layout_widgets_by_permission(layout_dict: dict, user_perms: set, role_slug: str) -> dict:
    """Elimina o marca no visibles los widgets de un layout para los cuales el usuario no tiene permiso."""
    from dashboard.permissions import check_widget_permission

    out = deepcopy(layout_dict)
    valid_widgets = []
    for w in out.get("widgets") or []:
        wkey = w.get("widgetKey")
        wdef = WIDGET_CATALOG.get(wkey)
        if not wdef:
            continue
        if check_widget_permission(user_perms, wdef, role_slug):
            valid_widgets.append(w)
    out["widgets"] = valid_widgets
    return out
